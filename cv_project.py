def select_instances_by_text(instances,text_label_list):
    if isinstance(text_label_list,str): text_label_list=[text_label_list.lower()]
    combined=None; selected=[]
    for inst in instances:
        if inst['label'].lower() in text_label_list:
            if combined is None: combined=inst['mask'].copy()
            else: combined|=inst['mask']
            selected.append(inst)
    if combined is None:
        size0=instances[0]['mask'].shape if len(instances)>0 else (512,512)
        combined=np.zeros(size0,dtype=bool)
    return combined,selected

