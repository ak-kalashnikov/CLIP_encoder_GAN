def get_room_layout_skeleton(img_path, out_size=(512,512)):
    img=cv2.imread(img_path); gray=cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    edges=cv2.Canny(gray,50,150)
    lines=cv2.HoughLinesP(edges,rho=1,theta=np.pi/180,threshold=80,minLineLength=50,maxLineGap=10)
    sk=np.zeros_like(img); line_list=[]
    if lines is not None:
        for l in lines:
            x1,y1,x2,y2=l[0]; line_list.append((int(x1),int(y1),int(x2),int(y2)))
            cv2.line(sk,(x1,y1),(x2,y2),(0,255,0),2)
    sk=ensure_size(sk,out_size)
    return sk,line_list

