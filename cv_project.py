def get_segmentation(image_path, resize=(512,416)):
    img = Image.open(image_path).convert("RGB")
    input_tensor = seg_transform(img).unsqueeze(0).to(device)
    with torch.no_grad():
        output = deeplab_model(input_tensor)['out'][0]
    seg_map = output.argmax(0).byte().cpu().numpy()
    seg_color = cv2.applyColorMap(seg_map, cv2.COLORMAP_JET)
    seg_color = cv2.resize(seg_color, resize)
