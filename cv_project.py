def get_normal_map_from_depth(depth_bgr):
    depth = cv2.cvtColor(depth_bgr, cv2.COLOR_BGR2GRAY).astype(np.float32)/255.0
    dzdx = cv2.Sobel(depth, cv2.CV_32F, 1, 0, 3)
    dzdy = cv2.Sobel(depth, cv2.CV_32F, 0, 1, 3)
    nx = -dzdx; ny = -dzdy; nz = np.ones_like(depth)
    norm = np.sqrt(nx*nx + ny*ny + nz*nz) + 1e-8
    nx/=norm; ny/=norm; nz/=norm
    normal_vis = (np.stack([(nx+1)/2, (ny+1)/2, (nz+1)/2], axis=-1)*255).astype(np.uint8)
    return cv2.cvtColor(normal_vis, cv2.COLOR_RGB2BGR)

