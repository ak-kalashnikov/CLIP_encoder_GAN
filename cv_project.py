def pil_to_cv2(img_pil): return cv2.cvtColor(np.array(img_pil), cv2.COLOR_RGB2BGR)
def cv2_to_pil(img_cv2): return Image.fromarray(cv2.cvtColor(img_cv2, cv2.COLOR_BGR2RGB))

def ensure_size(img_cv2, target_size):
    """Resize image to target_size if larger than target_size, else keep original."""
    H, W = img_cv2.shape[:2]
    max_h, max_w = target_size
    if H > max_h or W > max_w:
        return cv2.resize(img_cv2, (max_w, max_h), interpolation=cv2.INTER_AREA)
    else:
        return img_cv2.copy()

