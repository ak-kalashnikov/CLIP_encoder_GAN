def get_instance_masks(img_path, score_thresh=0.6, out_size=(512,512)):
    pil = Image.open(img_path).convert("RGB")
    img_cv = pil_to_cv2(pil)
    inp = mask_transform(pil).to(device)
    with torch.no_grad():
        outputs = maskrcnn([inp])[0]
    masks = outputs['masks']; labels = outputs['labels'].cpu().numpy()
    scores = outputs['scores'].cpu().numpy(); boxes = outputs['boxes'].cpu().numpy()
    H,W = img_cv.shape[:2]; instances=[]; vis=np.zeros_like(img_cv)
    for i in range(len(masks)):
        if scores[i]<score_thresh: continue
        mask=(masks[i,0].cpu().numpy()>0.5).astype(np.uint8)*255
        mask_resized=cv2.resize(mask, out_size, interpolation=cv2.INTER_NEAREST).astype(bool)
        label=COCO_INSTANCE_CATEGORY_NAMES[labels[i]]
        instances.append({'mask':mask_resized,'label':label,'score':float(scores[i]),'bbox':boxes[i].tolist()})
        color=tuple(np.random.randint(50,230,size=3).tolist())
        vis[mask>0]=color
    vis=ensure_size(vis,out_size)
    return vis, instances

