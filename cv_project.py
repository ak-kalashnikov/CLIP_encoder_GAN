def generate_controlled_interior(
    layout_path,prompt,out_path="generated.png",
    use_depth=True,use_edges=True,use_seg=True,use_instance=False,
    instance_target_label=None,num_inference_steps=20,guidance_scale=7.5,
    map_size=(620,512)
):
    # --- Extract feature maps ---
    maps=[]; map_names=[]
    # Dynamically scale each control map to input image size if smaller than map_size
    img_pil=Image.open(layout_path).convert("RGB")
    H_img,W_img=img_pil.size
    scale_size=(min(H_img,map_size[0]),min(W_img,map_size[1]))

    if use_depth:
        depth=get_depth_map(layout_path,out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(depth,cv2.COLOR_BGR2RGB))); map_names.append("depth")
    if use_edges:
        edges=get_edges(layout_path,out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(edges,cv2.COLOR_BGR2RGB))); map_names.append("canny")
    if use_seg:
        seg_color,seg_raw=get_semantic_segmentation(layout_path,out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(seg_color,cv2.COLOR_BGR2RGB))); map_names.append("seg")

    instance_vis=None; selected_instances=None
    if use_instance:
        vis,instances=get_instance_masks(layout_path,score_thresh=0.5,out_size=scale_size)
        instance_vis=vis
        if instance_target_label:
            combined_mask,selected_instances=select_instances_by_text(instances,instance_target_label)
            instance_mask_img=cv2.cvtColor((combined_mask.astype(np.uint8)*255),cv2.COLOR_GRAY2BGR)
            maps.append(Image.fromarray(cv2.cvtColor(instance_mask_img,cv2.COLOR_BGR2RGB)))
            map_names.append("instance_mask")
        else:
            maps.append(Image.fromarray(cv2.cvtColor(instance_vis,cv2.COLOR_BGR2RGB)))
            map_names.append("instances")

    # --- Build pipeline ---
    pipe=build_pipe(use_depth,use_edges,use_seg,use_instance)

    # --- Run generation ---
    # Ensure number of maps == number of controlnets
    maps_for_pipe=maps[:len(pipe.controlnet.nets)]
    print("Maps used:", map_names)
    out=pipe(prompt=prompt,image=maps_for_pipe,num_inference_steps=num_inference_steps,guidance_scale=guidance_scale)
    generated=out.images[0]
    generated.save(out_path)
    print("Saved:",out_path)
    return {"generated_pil":generated,"maps_cv2":{n:pil_to_cv2(maps[i]) for i,n in enumerate(map_names) if i<len(maps)},"instance_vis_cv2":instance_vis,"selected_instances":selected_instances}

