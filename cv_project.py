# 1) DEPTH MAP (MiDaS) - function accepts PIL path or PIL.Image

def get_depth_map(input_image, out_size=DEFAULT_MAP_SIZE, model_name=MIDAS_MODEL):
    global midas, midas_transform
    if midas is None:
        midas, midas_transform = load_midas(model_name, device=DEVICE)
    # accept path or PIL
    if isinstance(input_image, str):
        pil = Image.open(input_image).convert("RGB")
    else:
        pil = input_image.convert("RGB")
    img_np = np.array(pil)
    inp = midas_transform(img_np).to(DEVICE)
    with torch.no_grad():
        pred = midas(inp)
        pred = torch.nn.functional.interpolate(
            pred.unsqueeze(1),
            size=img_np.shape[:2],
            mode="bicubic",
            align_corners=False
        ).squeeze()
    depth = cv2.normalize(pred.cpu().numpy(), None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    depth_bgr = cv2.cvtColor(depth, cv2.COLOR_GRAY2BGR)
    return ensure_size(depth_bgr, out_size)


# 2) NORMAL MAP (from depth)

def get_normal_map_from_depth(depth_bgr):
    depth = cv2.cvtColor(depth_bgr, cv2.COLOR_BGR2GRAY).astype(np.float32)/255.0
    dzdx = cv2.Sobel(depth, cv2.CV_32F, 1, 0, 3)
    dzdy = cv2.Sobel(depth, cv2.CV_32F, 0, 1, 3)
    nx = -dzdx; ny = -dzdy; nz = np.ones_like(depth)
    norm = np.sqrt(nx*nx + ny*ny + nz*nz) + 1e-8
    nx/=norm; ny/=norm; nz/=norm
    normal_vis = (np.stack([(nx+1)/2, (ny+1)/2, (nz+1)/2], axis=-1)*255).astype(np.uint8)
    return cv2.cvtColor(normal_vis, cv2.COLOR_RGB2BGR)


# 3) CANNY EDGES (modular params)

def get_edges(input_image, out_size=DEFAULT_MAP_SIZE, low=100, high=200):
    if isinstance(input_image, str):
        img = cv2.imread(input_image)
    else:
        img = pil_to_cv2(input_image)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    edges = cv2.Canny(gray, low, high)
    edges_bgr = cv2.cvtColor(edges, cv2.COLOR_GRAY2BGR)
    return ensure_size(edges_bgr, out_size)


# 4) SEMANTIC SEGMENTATION (DeepLabv3)

def get_semantic_segmentation(input_image, out_size=DEFAULT_MAP_SIZE, colormap=cv2.COLORMAP_JET):
    global deeplab, seg_preprocess
    if deeplab is None:
        deeplab, seg_preprocess = load_deeplab(device=DEVICE)
    pil = Image.open(input_image).convert("RGB") if isinstance(input_image, str) else input_image.convert("RGB")
    inp = seg_preprocess(pil).unsqueeze(0).to(DEVICE)
    with torch.no_grad():
        out = deeplab(inp)['out'][0]
    seg = out.argmax(0).byte().cpu().numpy()
    seg_color = cv2.applyColorMap(seg.astype(np.uint8), colormap)
    return ensure_size(seg_color, out_size), seg


