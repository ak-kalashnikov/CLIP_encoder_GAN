def get_depth_map(img_path, out_size=(512,512)):
    pil = Image.open(img_path).convert("RGB")
    img_np = np.array(pil)
    inp = midas_transform(img_np).to(device)
    with torch.no_grad():
        pred = midas(inp)
        pred = torch.nn.functional.interpolate(
            pred.unsqueeze(1),
            size=img_np.shape[:2],
            mode="bicubic",
            align_corners=False
        ).squeeze()
    depth = cv2.normalize(pred.cpu().numpy(), None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    depth_bgr = cv2.cvtColor(depth, cv2.COLOR_GRAY2BGR)
    depth_bgr = ensure_size(depth_bgr, out_size)
    return depth_bgr

