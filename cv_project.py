# Helpers

def pil_to_cv2(img_pil): return cv2.cvtColor(np.array(img_pil), cv2.COLOR_RGB2BGR)
def cv2_to_pil(img_cv2): return Image.fromarray(cv2.cvtColor(img_cv2, cv2.COLOR_BGR2RGB))

def ensure_size(img_cv2, target_size):
    """target_size: (max_w, max_h). If image larger than either, resize proportionally to fit within."""
    max_w, max_h = target_size
    H, W = img_cv2.shape[:2]
    scale = min(1.0, min(max_w / float(W), max_h / float(H)))
    if scale < 1.0:
        new_w, new_h = int(W * scale), int(H * scale)
        return cv2.resize(img_cv2, (new_w, new_h), interpolation=cv2.INTER_AREA)
    return img_cv2.copy()


