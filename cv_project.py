def load_controlnet(name, device=DEVICE):
    try:
        print("Loading ControlNet:", name)
        cn = ControlNetModel.from_pretrained(name)
        return cn.to(device)
    except Exception as e:
        print("ControlNet load failed:", name, e)
        return None

# You can choose to load only the ControlNets you need at runtime to save RAM

CONTROLNET_REGISTRY = {
    "depth": "lllyasviel/sd-controlnet-depth",
    "canny": "lllyasviel/sd-controlnet-canny",
    "seg":   "lllyasviel/sd-controlnet-seg"
}

def build_pipe(control_keys, hf_model="runwayml/stable-diffusion-v1-5", device=DEVICE, low_cpu_mem=False):
    controls = []
    for k in control_keys:
        name = CONTROLNET_REGISTRY.get(k)
        if name:
            cn = load_controlnet(name, device=torch.device("cpu") if device.type=="cpu" else device)
            if cn is not None:
                controls.append(cn)
    # pass list if multiple controlnets
    pipe = StableDiffusionControlNetPipeline.from_pretrained(hf_model, controlnet=controls, safety_checker=None, torch_dtype=torch.float32)
    pipe = pipe.to(device)
    pipe.enable_attention_slicing()
    # try optional offload to reduce peak RAM (if supported)
    try:
        pipe.enable_model_cpu_offload()
    except Exception:
        pass
    return pipe


# 9) MASTER GENERATION (fixed ordering and robust controlnet->maps matching)

def generate_controlled_interior(
    layout_path, prompt, out_path="generated.png",
    use_depth=True, use_edges=True, use_seg=True, use_instance=False,
    instance_target_label=None, num_inference_steps=20, guidance_scale=7.5,
    map_size=DEFAULT_MAP_SIZE, hf_model="runwayml/stable-diffusion-v1-5",
    control_keys_order=None
):
    # map_size is (max_w, max_h)
    if control_keys_order is None:
        control_keys_order = []
        if use_depth: control_keys_order.append("depth")
        if use_edges: control_keys_order.append("canny")
        if use_seg: control_keys_order.append("seg")
        if use_instance: control_keys_order.append("instances")

    maps = []; map_names = []
    img_pil = Image.open(layout_path).convert("RGB")
    W_img, H_img = img_pil.size

    # compute scale_size (width,height) that fits within map_size and original

    max_w, max_h = map_size
    scale_w = min(W_img, max_w); scale_h = min(H_img, max_h)
    scale_size = (scale_w, scale_h)

    # Create maps following a deterministic order (so user can control which ControlNet gets which map)
    if use_depth:
        depth = get_depth_map(img_pil, out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(depth, cv2.COLOR_BGR2RGB))); map_names.append("depth")
    if use_edges:
        edges = get_edges(img_pil, out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(edges, cv2.COLOR_BGR2RGB))); map_names.append("canny")
    if use_seg:
        seg_color, seg_raw = get_semantic_segmentation(img_pil, out_size=scale_size)
        maps.append(Image.fromarray(cv2.cvtColor(seg_color, cv2.COLOR_BGR2RGB))); map_names.append("seg")
    instance_vis = None; selected_instances = None
    if use_instance:
        vis, instances = get_instance_masks(img_pil, score_thresh=0.5, out_size=scale_size)
        instance_vis = vis
        if instance_target_label:
            combined_mask, selected_instances = select_instances_by_text(instances, instance_target_label)
            instance_mask_img = cv2.cvtColor((combined_mask.astype(np.uint8)*255), cv2.COLOR_GRAY2BGR)
            maps.append(Image.fromarray(cv2.cvtColor(instance_mask_img, cv2.COLOR_BGR2RGB))); map_names.append("instance_mask")
        else:
            maps.append(Image.fromarray(cv2.cvtColor(instance_vis, cv2.COLOR_BGR2RGB))); map_names.append("instances")

    # Build pipeline with only requested controlnets (order matters)
    pipe = build_pipe(control_keys_order, hf_model=hf_model, device=DEVICE)

    # Robustly match maps -> controlnets: use min length
    try:
        n_cn = len(getattr(pipe.controlnet, "nets", pipe.controlnet))
    except Exception:
        n_cn = len(maps)
    # fallback safe slicing
    maps_for_pipe = maps[:max(1, min(len(maps), n_cn))]

    print("Maps used (names):", map_names)
    # Run generation (be mindful: on CPU this is very slow and may OOM)
    with torch.no_grad():
        out = pipe(prompt=prompt, image=maps_for_pipe, num_inference_steps=num_inference_steps, guidance_scale=guidance_scale)
    generated = out.images[0]
    generated.save(out_path)
    print("Saved:", out_path)

    return {
        "generated_pil": generated,
        "maps_cv2": {n: pil_to_cv2(maps[i]) for i, n in enumerate(map_names) if i < len(maps)},
        "instance_vis_cv2": instance_vis,
        "selected_instances": selected_instances
    }


