def build_pipe(use_depth=True,use_edges=True,use_seg=True,use_instance=False):
    controls=[]
    if use_depth: controls.append(controlnet_depth)
    if use_edges: controls.append(controlnet_canny)
    if use_seg and controlnet_seg is not None: controls.append(controlnet_seg)
