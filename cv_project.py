def load_midas(model_name=MIDAS_MODEL, device=DEVICE):
    print("Loading MiDaS:", model_name)
    midas = torch.hub.load("intel-isl/MiDaS", model_name).to(device).eval()
    midas_transforms = torch.hub.load("intel-isl/MiDaS", "transforms")
